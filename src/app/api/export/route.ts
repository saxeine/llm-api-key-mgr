import { NextRequest, NextResponse } from "next/server";
import { getWorkspaceData } from "@/lib/workspace";

export const dynamic = "force-dynamic";

export async function GET(request: NextRequest) {
  try {
    const sp = request.nextUrl.searchParams;
    const format = sp.get("format") || "env"; // env | shell | json
    const environment = sp.get("environment") || "all";
    const masked = sp.get("masked") === "true";
    const idsParam = sp.get("ids");
    const download = sp.get("download") === "true";

    const workspace = await getWorkspaceData({ includeRawKeys: !masked });
    const providerMap = new Map(workspace.providers.map((p) => [p.id, p]));
    const modelMap = new Map(workspace.models.map((m) => [m.id, m]));

    const allowedIds = idsParam
      ? new Set(
          idsParam
            .split(",")
            .map((v) => Number(v.trim()))
            .filter((n) => Number.isInteger(n) && n > 0)
        )
      : null;

    const selectedKeys = workspace.keys.filter((k) => {
      if (allowedIds && !allowedIds.has(k.id)) return false;
      if (environment !== "all" && k.environment !== environment) return false;
      return true;
    });

    // Track duplicate env var names so multiple keys for same provider don't silently clobber each other
    const usedEnvCounts = new Map<string, number>();

    let content = "";
    let filename = ".env.test";
    let mimeType = "text/plain; charset=utf-8";

    if (format === "json") {
      filename = "llm-test-keys.json";
      mimeType = "application/json; charset=utf-8";
      const payload = {
        exportedAt: new Date().toISOString(),
        source: "KeyBench LLM Test Vault",
        count: selectedKeys.length,
        keys: selectedKeys.map((k) => {
          const prov = providerMap.get(k.providerId);
          const applicableModels = workspace.models
            .filter(
              (m) =>
                (m.providerId === k.providerId && k.scopeMode === "all_provider") ||
                k.linkedModelIds.includes(m.id)
            )
            .map((m) => m.apiModelId);

          return {
            label: k.label,
            provider: prov?.name || k.providerId,
            environment: k.environment,
            envVar: k.effectiveEnvVar,
            apiKey: masked ? k.maskedKey : k.rawKey,
            baseUrl: k.effectiveBaseUrl,
            models:
              k.linkedModelIds.length > 0 && k.scopeMode === "selected_models"
                ? k.linkedModelIds
                    .map((id) => modelMap.get(id)?.apiModelId)
                    .filter(Boolean)
                : applicableModels,
            notes: k.notes,
          };
        }),
      };
      content = JSON.stringify(payload, null, 2);
    } else {
      const isShell = format === "shell";
      filename = isShell ? "llm-keys.sh" : ".env.test";
      const header = [
        isShell ? "#!/usr/bin/env bash" : null,
        `# Generated by KeyBench — LLM Test Key Vault (${selectedKeys.length} key${selectedKeys.length === 1 ? "" : "s"})`,
        "",
      ]
        .filter((l) => l !== null)
        .join("\n");

      const blocks = selectedKeys.map((k) => {
        const prov = providerMap.get(k.providerId);
        const count = (usedEnvCounts.get(k.effectiveEnvVar) ?? 0) + 1;
        usedEnvCounts.set(k.effectiveEnvVar, count);
        const varName =
          count === 1
            ? k.effectiveEnvVar
            : `${k.effectiveEnvVar}_${k.environment.toUpperCase()}_${count}`;
        const val = masked ? k.maskedKey : k.rawKey ?? k.maskedKey;
        const escaped = val.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
        const prefix = isShell ? "export " : "";
        return `# ${prov?.name ?? k.providerId} — ${k.label} [${k.environment}]\n${prefix}${varName}="${escaped}"`;
      });

      content =
        selectedKeys.length === 0
          ? "# No keys matched the current filter."
          : `${header}\n${blocks.join("\n\n")}\n`;
    }

    if (download) {
      return new NextResponse(content, {
        status: 200,
        headers: {
          "Content-Type": mimeType,
          "Content-Disposition": `attachment; filename="${filename}"`,
        },
      });
    }

    return NextResponse.json({
      format,
      filename,
      count: selectedKeys.length,
      content,
    });
  } catch (error) {
    console.error("GET /api/export failed:", error);
    return NextResponse.json({ error: "Failed to generate export." }, { status: 500 });
  }
}
